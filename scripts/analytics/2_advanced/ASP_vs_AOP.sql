Imagine you are selling Water Bottles or Socks.A customer places 1 Order.
In that order, they buy 10 Water Bottles at $5 each.Total Sales = $50.
The Math:
    ASP (Price per bottle): 50 / 10 = 5
    AOR (Revenue per receipt): 50 / 1 = 50
If you only looked at ASP, you'd think the customer is "low value" ($5). 
If you look at AOR, you see they are actually a "high value" visit ($50).
